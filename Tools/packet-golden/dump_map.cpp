// Map server packets: src/map/clif_packetdb.hpp and src/map/packets.hpp.
//
// Compiled against the rAthena headers with -DPACKETVER=20211103 (the same define
// `./configure --enable-packetver=20211103` passes). Prints the packet table as
// rAthena's map server builds it, HEADER_* values, struct sizes and golden packet
// encodings, see emit.hpp for the record format.
//
// The packet table is not parsed: clif_packetdb.hpp and clif_shuffle.hpp are #included
// inside a function exactly like clif.cpp does in packetdb_readdb(), with
// packetdb_addpacket() turned into a recorder, so the compiler resolves every #if PACKETVER block, every
// sizeof(PACKET_...) and every HEADER_* constant.
//
// GPL-3.0, derived from rAthena.

#include <map>
#include <string>
#include <vector>

#include "map/clif.hpp"

#include "emit.hpp"

using golden::copy_string;
using golden::emit_blob;

namespace {

struct Entry {
	int length = 0;
	std::string function;       // empty when the packet has no parse function
	std::vector<int> offsets;   // as written in clif_packetdb.hpp, without the 0 terminator
	int sequence = 0;           // order of the last registration of this opcode
	std::string expression;     // the opcode as written: 0x0064, HEADER_ZC_NOTIFY_TIME, idle_unitType, ...
};

std::map<int, Entry> table;
int next_sequence = 0;

/// Same bounds and last-registration-wins behavior as packetdb_addpacket() in clif.cpp.
void record(int cmd, const char* expression, int length, const char* function, std::vector<int> args) {
	if (cmd <= 0 || cmd > MAX_PACKET_DB) {
		return;
	}
	if (!args.empty()) {
		args.pop_back();  // the terminating 0 appended by the parseable_packet/packet macros
	}
	Entry entry;
	entry.length = length;
	entry.function = std::string(function) == "nullptr" ? "" : function;
	entry.offsets = args;
	entry.sequence = next_sequence++;
	entry.expression = expression;
	table[cmd] = entry;
}

// clif_packetdb.hpp defines packet() and parseable_packet() on top of packetdb_addpacket().
// Turn that into a recorder. The function argument is only stringified, so the
// clif_parse_* functions do not need to exist.
#define packetdb_addpacket(cmd, len, func, ...) \
	record(static_cast<int>(cmd), #cmd, static_cast<int>(len), #func, std::vector<int>{__VA_ARGS__})

// clif.cpp includes clif_packetdb.hpp and then clif_shuffle.hpp (the per-PACKETVER opcodes,
// for versions it does not list the plain, unshuffled ones) inside packetdb_readdb().
void read_packet_db() {
#include "map/clif_packetdb.hpp"
#include "map/clif_shuffle.hpp"
}

#undef packetdb_addpacket
#undef packet
#undef parseable_packet

}  // namespace

// ---------------------------------------------------------------------------
// Position packing, verbatim from src/map/clif.cpp (static inline there).
// ---------------------------------------------------------------------------

static inline void WBUFPOS(uint8* p, uint16 pos, int16 x, int16 y, unsigned char dir) {
	p += pos;
	p[0] = (uint8)(x>>2);
	p[1] = (uint8)((x<<6) | ((y>>4)&0x3f));
	p[2] = (uint8)((y<<4) | (dir&0xf));
}

static inline void WBUFPOS2(uint8* p, uint16 pos, int16 x0, int16 y0, int16 x1, int16 y1, uint8 sx0, uint8 sy0) {
	p += pos;
	p[0] = (uint8)(x0>>2);
	p[1] = (uint8)((x0<<6) | ((y0>>4)&0x3f));
	p[2] = (uint8)((y0<<4) | ((x1>>6)&0x0f));
	p[3] = (uint8)((x1<<2) | ((y1>>8)&0x03));
	p[4] = (uint8)y1;
	p[5] = (uint8)((sx0<<4) | (sy0&0x0f));
}

// names.inc is generated by generate.sh from the preprocessed header:
//   GOLDEN_HEADER(<name without HEADER_>) and GOLDEN_STRUCT(<struct name>)
static void dump_names() {
#define GOLDEN_HEADER(n) std::printf("@hdr\tHEADER_" #n "\t%d\n", static_cast<int>(HEADER_##n));
#define GOLDEN_STRUCT(n) std::printf("@size\t" #n "\t%zu\n", sizeof(n));
#include "names.inc"
#undef GOLDEN_HEADER
#undef GOLDEN_STRUCT
}

static void dump_table() {
	// "latest" marks the last registration of a parse function: clif_packetdb.hpp keeps
	// every older opcode of a packet that was renumbered (0x72 and 0x436 both map to
	// clif_parse_WantToConnection) but the client of this PACKETVER only sends the newest one.
	std::map<std::string, int> latest_sequence;
	for (const auto& [cmd, entry] : table) {
		if (!entry.function.empty() && entry.sequence >= latest_sequence[entry.function]) {
			latest_sequence[entry.function] = entry.sequence;
		}
	}
	for (const auto& [cmd, entry] : table) {
		std::string offsets;
		for (size_t i = 0; i < entry.offsets.size(); i++) {
			offsets += (i ? "," : "") + std::to_string(entry.offsets[i]);
		}
		const bool latest = !entry.function.empty() && latest_sequence[entry.function] == entry.sequence;
		std::printf("@pkt\t%d\t%d\t%s\t%s\t%d\t%s\n", cmd, entry.length,
			entry.function.empty() ? "-" : entry.function.c_str(),
			offsets.empty() ? "-" : offsets.c_str(), latest ? 1 : 0, entry.expression.c_str());
	}
}

/// The newest opcode (last registration in clif_packetdb.hpp) that rAthena parses with `function`.
static int latest_opcode(const char* function) {
	int found = 0;
	int sequence = -1;
	for (const auto& [cmd, entry] : table) {
		if (entry.function == function && entry.sequence > sequence) {
			found = cmd;
			sequence = entry.sequence;
		}
	}
	if (found == 0) {
		std::fprintf(stderr, "dump_map: no packet registered for %s\n", function);
		std::exit(1);
	}
	return found;
}

/// Allocates a zeroed client -> server packet of the length the table gives for `cmd`,
/// with the packet type written at offset 0.
static std::vector<uint8_t> raw_packet(int cmd, const char* expected_function) {
	const Entry& entry = table.at(cmd);
	if (entry.function != expected_function) {
		std::fprintf(stderr, "dump_map: 0x%04x is not %s\n", cmd, expected_function);
		std::exit(1);
	}
	std::vector<uint8_t> buf(entry.length > 0 ? entry.length : 4, 0);
	golden::put_u16(buf, 0, static_cast<uint16_t>(cmd));
	return buf;
}

static void dump_golden() {
	// CZ_ENTER (clif_parse_WantToConnection), parsed with RFIFOx at the table's offsets.
	{
		const int cmd = latest_opcode("clif_parse_WantToConnection");
		const Entry& e = table.at(cmd);
		std::vector<uint8_t> buf = raw_packet(cmd, "clif_parse_WantToConnection");
		golden::put_u32(buf, e.offsets.at(0), 2000001);     // account id
		golden::put_u32(buf, e.offsets.at(1), 150000);      // char id
		golden::put_u32(buf, e.offsets.at(2), 0x11223344);  // login id 1 (auth code)
		golden::put_u32(buf, e.offsets.at(3), 123456);      // client tick
		buf[e.offsets.at(4)] = 1;                           // sex
		emit_blob("CZ_ENTER", buf, "type.W AID.L CID.L login_id1.L clienttick.L (padding) sex.B at offsets from the packet table");
	}

	// ZC_ACCEPT_ENTER (clif_authok).
	{
		PACKET_ZC_ACCEPT_ENTER p{};
		p.packetType = HEADER_ZC_ACCEPT_ENTER;
		p.startTime = 123456;
		WBUFPOS(p.posDir, 0, 150, 200, 3);
		p.xSize = 5;
		p.ySize = 5;
#if PACKETVER >= 20080102
		p.font = 2;
#endif
#if PACKETVER >= 20141016 && PACKETVER < 20160330
		p.sex = 1;
#endif
		emit_blob("ZC_ACCEPT_ENTER", &p, sizeof(p), "type.W starttime.L position.3B(x=150,y=200,dir=3) xsize.B ysize.B font.W");
	}

	// CZ_REQUEST_MOVE (clif_parse_WalkToXY), position packed with WBUFPOS.
	{
		const int cmd = latest_opcode("clif_parse_WalkToXY");
		const Entry& e = table.at(cmd);
		std::vector<uint8_t> buf = raw_packet(cmd, "clif_parse_WalkToXY");
		WBUFPOS(buf.data() + e.offsets.at(0), 0, 300, 500, 0);
		emit_blob("CZ_REQUEST_MOVE", buf, "type.W position.3B(x=300,y=500,dir=0)");
	}

	// ZC_NOTIFY_PLAYERMOVE (clif_walkok), positions packed with WBUFPOS2.
	{
		PACKET_ZC_NOTIFY_PLAYERMOVE p{};
		p.packetType = HEADER_ZC_NOTIFY_PLAYERMOVE;
		p.moveStartTime = 123456;
		WBUFPOS2(p.moveData, 0, 150, 200, 153, 203, 8, 8);
		emit_blob("ZC_NOTIFY_PLAYERMOVE", &p, sizeof(p), "type.W starttime.L movedata.6B(from 150,200 to 153,203, sx0=8, sy0=8)");
	}

	// CZ_REQUEST_CHAT (clif_parse_GlobalMessage): "<name> : <message>", no zero terminator
	// at PACKETVER >= 20151001 (see clif_process_message).
	{
		const int cmd = latest_opcode("clif_parse_GlobalMessage");
		const Entry& e = table.at(cmd);
		const std::string text = "Alice : Hello, world!";
		std::vector<uint8_t> buf = raw_packet(cmd, "clif_parse_GlobalMessage");
		buf.resize(4 + text.size());
		golden::put_u16(buf, e.offsets.at(0), static_cast<uint16_t>(buf.size()));
		std::memcpy(buf.data() + e.offsets.at(1), text.data(), text.size());
		emit_blob("CZ_REQUEST_CHAT", buf, "type.W length.W text.?B (\"<name> : <message>\", no terminator)");
	}

	// ZC_NOTIFY_PLAYERCHAT (clif_displaymessage): <length>.W <message>.?B, zero terminated.
	{
		const char* message = "Alice : Hello, world!";
		const size_t len = std::strlen(message) + 1;
		std::vector<uint8_t> buf(sizeof(PACKET_ZC_NOTIFY_PLAYERCHAT) + len, 0);
		auto* p = reinterpret_cast<PACKET_ZC_NOTIFY_PLAYERCHAT*>(buf.data());
		p->PacketType = 0x8e;  // no HEADER_ constant in rAthena, clif_displaymessage writes the literal
		p->PacketLength = static_cast<int16>(buf.size());
		std::memcpy(p->Message, message, len);
		emit_blob("ZC_NOTIFY_PLAYERCHAT", buf, "type.W length.W message.?B (zero terminated)");
	}

	// ZC_NOTIFY_CHAT (clif_GlobalMessage): <length>.W <GID>.L <message>.?B, zero terminated.
	{
		const char* message = "Hello";
		const size_t len = std::strlen(message) + 1;
		std::vector<uint8_t> buf(sizeof(PACKET_ZC_NOTIFY_CHAT) + len, 0);
		auto* p = reinterpret_cast<PACKET_ZC_NOTIFY_CHAT*>(buf.data());
		p->PacketType = HEADER_ZC_NOTIFY_CHAT;
		p->PacketLength = static_cast<int16>(buf.size());
		p->GID = 150000;
		std::memcpy(p->Message, message, len);
		emit_blob("ZC_NOTIFY_CHAT", buf, "type.W length.W GID.L message.?B (zero terminated)");
	}

	// CZ_REQUEST_TIME (clif_parse_TickSend).
	{
		const int cmd = latest_opcode("clif_parse_TickSend");
		const Entry& e = table.at(cmd);
		std::vector<uint8_t> buf = raw_packet(cmd, "clif_parse_TickSend");
		golden::put_u32(buf, e.offsets.at(0), 123456);
		emit_blob("CZ_REQUEST_TIME", buf, "type.W clienttick.L");
	}

	// ZC_NOTIFY_TIME (clif_notify_time).
	{
		PACKET_ZC_NOTIFY_TIME p{};
		p.packetType = HEADER_ZC_NOTIFY_TIME;
		p.time = 654321;
		emit_blob("ZC_NOTIFY_TIME", &p, sizeof(p), "type.W time.L");
	}
}

int main() {
	read_packet_db();
	dump_names();
	dump_table();
	dump_golden();
	return 0;
}
