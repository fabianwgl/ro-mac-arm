// Login and char server packets: src/common/packets.hpp.
//
// Compiled against the rAthena headers with -DPACKETVER=20211103 (the same define
// `./configure --enable-packetver=20211103` passes). Prints HEADER_* values, struct
// sizes and golden packet encodings, see emit.hpp for the record format.
//
// src/common/packets.hpp and src/map/packets.hpp share an include guard, so the map
// packets are dumped by dump_map.cpp, a separate translation unit.
//
// GPL-3.0, derived from rAthena.

#include <common/packets.hpp>

#include "emit.hpp"

using golden::copy_string;
using golden::emit_blob;

// names.inc is generated by generate.sh from the preprocessed header:
//   GOLDEN_HEADER(<name without HEADER_>) and GOLDEN_STRUCT(<struct name>)
static void dump_names() {
#define GOLDEN_HEADER(n) std::printf("@hdr\tHEADER_" #n "\t%d\n", static_cast<int>(HEADER_##n));
#define GOLDEN_STRUCT(n) std::printf("@size\t" #n "\t%zu\n", sizeof(n));
#include "names.inc"
#undef GOLDEN_HEADER
#undef GOLDEN_STRUCT
}

