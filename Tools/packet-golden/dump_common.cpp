static void dump_golden() {
	// CA_LOGIN: client -> login server, fixed size.
	{
		PACKET_CA_LOGIN p{};
		p.packetType = HEADER_CA_LOGIN;
		p.version = 20211103;
		copy_string(p.username, "ratest");
		copy_string(p.password, "secret");
		p.clienttype = 22;
		emit_blob("CA_LOGIN", &p, sizeof(p), "type.W version.L username.24B password.24B clienttype.B");
	}

	// AC_ACCEPT_LOGIN: login server -> client, variable length, one char server entry.
	{
		std::vector<uint8_t> buf(sizeof(PACKET_AC_ACCEPT_LOGIN) + sizeof(PACKET_AC_ACCEPT_LOGIN_sub));
		auto* p = reinterpret_cast<PACKET_AC_ACCEPT_LOGIN*>(buf.data());
		p->packetType = HEADER_AC_ACCEPT_LOGIN;
		p->packetLength = static_cast<int16>(buf.size());
		p->login_id1 = 0x11223344;
		p->AID = 2000001;
		p->login_id2 = 0x55667788;
		p->last_ip = 0x0100007f;
		copy_string(p->last_login, "2021-11-03 12:34:56");
		p->sex = 1;
		copy_string(p->token, "abcdef0123456789");
		p->char_servers[0].ip = 0x0100007f;
		p->char_servers[0].port = 6121;
		copy_string(p->char_servers[0].name, "rAthena");
		p->char_servers[0].users = 5;
		p->char_servers[0].type = 3;
		p->char_servers[0].new_ = 1;
		emit_blob("AC_ACCEPT_LOGIN", buf,
			"type.W length.W login_id1.L AID.L login_id2.L last_ip.L last_login.26B sex.B token.17B "
			"{ ip.L port.W name.20B users.W type.W new.W unknown.128B }*1");
	}

	// CH_ENTER: client -> char server. rAthena parses it with RFIFOx in
	// chclif_parse_reqtoconnect (no struct): 0065, length 17.
	{
		std::vector<uint8_t> buf(17, 0);
		golden::put_u16(buf, 0, 0x65);
		golden::put_u32(buf, 2, 2000001);        // account id    (RFIFOL(fd,2))
		golden::put_u32(buf, 6, 0x11223344);     // login id 1    (RFIFOL(fd,6))
		golden::put_u32(buf, 10, 0x55667788);    // login id 2    (RFIFOL(fd,10))
		golden::put_u16(buf, 14, 22);            // client type   (not read by rAthena)
		buf[16] = 1;                             // sex           (RFIFOB(fd,16))
		emit_blob("CH_ENTER", buf, "type.W AID.L login_id1.L login_id2.L clienttype.W sex.B");
	}

	// HC_ACCEPT_ENTER (0x6b): the char list at PACKETVER >= 20130000, sent after HC_ACCEPT_ENTER2.
	{
		std::vector<uint8_t> buf(sizeof(PACKET_HC_ACCEPT_ENTER) + sizeof(CHARACTER_INFO));
		auto* p = reinterpret_cast<PACKET_HC_ACCEPT_ENTER*>(buf.data());
		p->packetType = HEADER_HC_ACCEPT_ENTER;
		p->packetLength = static_cast<int16>(buf.size());
#if PACKETVER >= 20100413
		p->total = 12;
		p->premium_start = 9;
		p->premium_end = 10;
#endif
		copy_string(p->extension, "");
		p->characters[0] = sample_character();
		emit_blob("HC_ACCEPT_ENTER", buf,
			"type.W length.W total.B premium_start.B premium_end.B extension.20B { CHARACTER_INFO }*1");
	}

	// HC_ACCEPT_ENTER2 (0x82d): slot counts, fixed size.
	{
		PACKET_HC_ACCEPT_ENTER2 p{};
		p.packetType = HEADER_HC_ACCEPT_ENTER2;
		p.packetLength = sizeof(p);
		p.normal = 9;
		p.premium = 1;
		p.billing = 2;
		p.producible = 3;
		p.total = 12;
		emit_blob("HC_ACCEPT_ENTER2", &p, sizeof(p),
			"type.W length.W normal.B premium.B billing.B producible.B total.B extension.20B");
	}

	// HC_ACK_CHARINFO_PER_PAGE (0xb72): paged char list, answer to CH_CHARLIST_REQ.
	{
		std::vector<uint8_t> buf(sizeof(PACKET_HC_ACK_CHARINFO_PER_PAGE) + sizeof(CHARACTER_INFO));
		auto* p = reinterpret_cast<PACKET_HC_ACK_CHARINFO_PER_PAGE*>(buf.data());
		p->packetType = HEADER_HC_ACK_CHARINFO_PER_PAGE;
		p->packetLength = static_cast<int16>(buf.size());
		p->characters[0] = sample_character();
		emit_blob("HC_ACK_CHARINFO_PER_PAGE", buf, "type.W length.W { CHARACTER_INFO }*1");
	}

	// HC_NOTIFY_ZONESVR: char server -> client, map server address.
	{
		PACKET_HC_NOTIFY_ZONESVR p{};
		p.packetType = HEADER_HC_NOTIFY_ZONESVR;
		p.CID = 150000;
		copy_string(p.mapname, "prontera.gat");
		p.ip = 0x0100007f;
		p.port = 5121;
		copy_string(p.domain, "ro.example.org");
		emit_blob("HC_NOTIFY_ZONESVR", &p, sizeof(p), "type.W CID.L mapname.16B ip.L port.W domain.128B");
	}

	// HC_SECOND_PASSWD_LOGIN: char server -> client, pincode state.
	{
		PACKET_HC_SECOND_PASSWD_LOGIN p{};
		p.packetType = HEADER_HC_SECOND_PASSWD_LOGIN;
		p.seed = 0xcafebabe;
		p.AID = 2000001;
		p.result = 1;
		emit_blob("HC_SECOND_PASSWD_LOGIN", &p, sizeof(p), "type.W seed.L AID.L result.W");
	}

	// CH_SECOND_PASSWD_ACK: client -> char server, pincode entry.
	{
		PACKET_CH_SECOND_PASSWD_ACK p{};
		p.packetType = HEADER_CH_SECOND_PASSWD_ACK;
		p.AID = 2000001;
		std::memcpy(p.pin, "1234", 4);
		emit_blob("CH_SECOND_PASSWD_ACK", &p, sizeof(p), "type.W AID.L pin.4B");
	}
}

int main() {
	dump_names();
	dump_golden();
	return 0;
}
